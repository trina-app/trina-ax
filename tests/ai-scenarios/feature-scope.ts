// How the team AI reaches each feature of the feature map (docs/features.ts), so the scenario catalog can be checked
// for coverage per feature (lib/coverage.ts; `bun run ai:scenarios coverage`). Every feature id of the map must be
// here: a new feature without a line fails the coverage check, like `features:check` fails an endpoint with no feature.
//
//   acts:     the AI does it with its own actions (the tools named); cases: the happy path, each place where the tool
//             set differs (personal / shared project chat / room ✦ side chat / guest, member vs admin), each install
//             where it differs, and a refusal where one applies
//   explains: the AI cannot do it itself but people ask it ("how do I …"); cases: a plain, correct explanation of where
//             it is, and a refusal for a person who may not do it, where that applies
//   none:     not something a person asks the team AI about (setup screens before there is a team, store listings,
//             release plumbing); no case, the reason is said here
