// Writes docs/site/reference/http-api.md from the API contract (shared/src/api). `bun run docs:api`.
// tests/unit/docs-site.test.ts fails when the committed page differs from what this produces.
import fs from 'node:fs'
import path from 'node:path'
import { API_GROUPS } from '../../shared/src/api/index'
import type { Endpoint } from '../../shared/src/api/endpoint'
import { ROOT } from './site'

export const API_REFERENCE_FILE = 'docs/site/reference/http-api.md'

const GROUP_TITLES: Record<keyof typeof API_GROUPS, string> = {
  AUTH: 'Setup, sign-in and account',
  CHATS: 'Chats and projects',
  MEMORIES: 'Memories',
  SKILLS: 'Skills',
  SCHEDULES: 'Scheduled tasks',
  CONNECTED: 'Connected folders',
  FILES: 'Files',
  ARTIFACTS: 'Artifacts',
  JOBS: 'Jobs',
  BROWSER: 'In-app browser',
  ADMIN: 'Admin',
  CREDENTIALS: 'AI connections',
  DRIVE: 'Google Drive',
  INTEGRATIONS: 'MCP and HTTP connections',
  NOTIFICATIONS: 'Notifications',
  PUSH: 'Push notifications',
  REMOTE_MCP: 'MCP connector (app connections)',
  SYSTEM: 'System',
  OFFICE_UPDATE: 'Office Mac updates',
  PLUGINS: 'Plugins',
  DEV_ENV: 'Dev environment',
  ONBOARDING_PACKS: 'Onboarding: skill packs',
  ONBOARDING: 'Onboarding (company profile)',
  TEAM_LINKS: 'Team invite link',
  WELCOME: 'Onboarding: welcome steps',
  ONBOARDING_GOAL: 'Onboarding: the 7-day team goal',
  DEMO: 'Demo mode (development demo server only)',
}

const WHO: Record<Endpoint['auth'], string> = {
  public: 'Anyone',
  user: 'Signed in',
  admin: 'Admin',
  owner: 'Owner',
  'owner-reauth': 'Owner + password',
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()

export function apiReferenceMarkdown(): string {
  const groups = Object.entries(API_GROUPS) as [keyof typeof API_GROUPS, Record<string, Endpoint>][]
  const total = groups.reduce((n, [, eps]) => n + Object.keys(eps).length, 0)
  const lines = [
    '---',
    'title: HTTP API',
    'description: Every endpoint of the team server, grouped by area, with who may call it. Generated from the API contract.',
    '---',
    '',
    '<!-- Generated by `bun run docs:api` from shared/src/api. Do not edit by hand. -->',
    '',
    `The team server has ${total} HTTP endpoints. Each one is declared once in [\`shared/src/api/\`](../../../shared/src/api/index.ts), with zod schemas for its query, body and response. The server validates every request against it, and the web app calls endpoints by name.`,
    '',
    ':::note',
    'The API serves the Trina AX apps. It is not yet a stable public API for other programs, and it follows the [version rules](../develop/versioning.md).',
    ':::',
    '',
    '## Calling the API',
    '',
    '- Endpoints live under the team\'s own address, for example `https://team.example.com/api/health`.',
    '- The web app signs in with a session cookie. Requests from other origins are refused unless the origin is in `MYCEL_PUBLIC_ORIGINS`.',
    '- Live updates and answers stream over a WebSocket at `GET /api/ws`.',
    '- The [MCP connector](../agents/mcp-connector.md) adds `/mcp`, `/oauth/*` and `/.well-known/*` outside this list.',
    '',
    '| Who | Means |',
    '|---|---|',
    '| Anyone | No session needed |',
    '| Signed in | Any active member |',
    '| Admin | An admin or the owner |',
    '| Owner | The owner only |',
    '| Owner + password | The owner, who enters their password again (updates, restores) |',
    '',
  ]
  for (const [key, eps] of groups) {
    const list = Object.values(eps)
    lines.push(`## ${GROUP_TITLES[key] ?? key}`, '', '| Method | Path | Who | What it does |', '|---|---|---|---|')
    for (const e of list) lines.push(`| \`${e.method}\` | \`${e.path}\` | ${WHO[e.auth]} | ${cell(e.summary)} |`)
    lines.push('')
  }
  return lines.join('\n')
}

if (import.meta.main) {
  fs.writeFileSync(path.join(ROOT, API_REFERENCE_FILE), apiReferenceMarkdown())
  console.log(`Wrote ${API_REFERENCE_FILE}`)
}
