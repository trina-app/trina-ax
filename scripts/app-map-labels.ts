// Writes server/src/chat/app-map-labels.ts: the words of the web app's labels the AI's map of the app names
// (server/src/chat/app-map.ts APP_MAP_KEYS), in every language, from web/src/i18n. `--check`: exit 1 when the file is
// not what this would write (tests/unit/ai-app-map.test.ts checks the same).
//   bun scripts/app-map-labels.ts [--check]
import fs from 'node:fs'
import path from 'node:path'
import { Locale } from '../shared/src/api'
import { DICTS } from '../web/src/i18n'
import { APP_MAP_KEYS } from '../server/src/chat/app-map'

export const LABELS_FILE = path.resolve(import.meta.dir, '../server/src/chat/app-map-labels.ts')

/** The file's text for these keys; throws on a key the web app does not have. */
export function appMapLabelsText(keys: readonly string[] = APP_MAP_KEYS): string {
  const rows = keys.map((k) => {
    const cells = Locale.options.map((l) => {
      const text = (DICTS[l] as Record<string, string | undefined>)[k]
      if (typeof text !== 'string') throw new Error(`web/src/i18n/${l}.ts has no "${k}" (server/src/chat/app-map.ts APP_MAP_KEYS)`)
      return `${l}: ${JSON.stringify(text)}`
    })
    return `  ${JSON.stringify(k)}: { ${cells.join(', ')} },`
  })
  return [
    '// Generated by scripts/app-map-labels.ts from web/src/i18n: do not edit. The words of the labels the AI\'s map of the',
    '// app names (app-map.ts APP_MAP_KEYS); tests/unit/ai-app-map.test.ts fails when this is not current.',
    "import type { Locale } from '@mycel/shared/api'",
    '',
    'export const APP_MAP_LABELS: Readonly<Record<string, Readonly<Record<Locale, string>>>> = {',
    ...rows,
    '}',
    '',
  ].join('\n')
}

if (import.meta.main) {
  const want = appMapLabelsText()
  const have = fs.existsSync(LABELS_FILE) ? fs.readFileSync(LABELS_FILE, 'utf8') : ''
  if (process.argv.includes('--check')) {
    if (want !== have) { console.error('server/src/chat/app-map-labels.ts is not current: run bun scripts/app-map-labels.ts'); process.exit(1) }
    console.log('app-map labels: current')
  } else if (want !== have) {
    fs.writeFileSync(LABELS_FILE, want)
    console.log('wrote server/src/chat/app-map-labels.ts')
  } else console.log('app-map labels: current')
}
