import { randomUUID } from 'node:crypto'
import { HWP_LIMITS as L } from '@mycel/shared/hwp'
import type { TeamFiles } from '../team-files/service'
import { converterCgroup } from '../system/cgroups'
import { authorize } from '../policy/authorize'
import { SearchAdmission } from './search-admission'
import { sha256 } from './store'
import { disabledHwpEngine, HwpError, type HwpEngine, type RenderedPage } from './hwp-engine'

/** A document to preview, opened for one person by a check made now: `key` names it in the cache (a team path, a room
 * file), `bytes` were read through the request's admission (bound to that check: no link, no swap, a quarantined hash
 * refused), `version` changes when the file behind it does. */
export interface HwpSource { key: string; bytes: Buffer; hash: string; version: string; ext: 'hwp' | 'hwpx' }
/** Opens a source and checks access to it, on every call: before any cache lookup or render, and again after the
 * render. Throws when the person may not read it (an HttpError, a ToolError or an HwpError). */
export type OpenHwpSource = (admission: SearchAdmission) => HwpSource

interface Cached { key: string; id: string; source: string; result: RenderedPage; expires: number }
/** Cache IDs are random and never capabilities. Every lookup opens and authorizes the source again.
 * The engine is resolved for every request (server/src/plugins: the HWP Preview plugin's package while it is on and
 * runnable here, otherwise the disabled engine). One cache, one renderer and the same limits for a team file and a file
 * sent in a room (rooms/files.ts hwpSource). */
export class HwpPreviews {
  private cache = new Map<string, Cached>()
  private running = new Set<string>()
  /** cancels the renders in flight (plugin turned off, removed, updated or rolled back) */
  private inflight = new Set<AbortController>()
  private generation = 0
  private resolve: () => HwpEngine
  constructor(private files: TeamFiles, engine: HwpEngine | (() => HwpEngine) = disabledHwpEngine) {
    this.resolve = typeof engine === 'function' ? engine : () => engine
  }
  get engine(): HwpEngine { return this.resolve() }
  /** Drop every cached page and cancel running renders; their results are discarded (generation check). */
  invalidate() {
    this.generation++; this.cache.clear()
    for (const c of this.inflight) c.abort()
    this.inflight.clear()
  }
  private source(user: string, source: string, admission: SearchAdmission): HwpSource {
    // Both browser preview and hwp_render converge here. Download permission is
    // insufficient: generated bytes renamed to .hwp/.hwpx remain quarantined.
    const allowed = () => authorize(this.files.fx, this.files.rules(), this.files.principal(user), source, 'read')
    const r = allowed(), f = { name: r.segs.at(-1)!, abs: r.abs }
    if (!/\.hwpx?$/i.test(f.name)) throw new HwpError('unsupported')
    if (r.st!.size > L.inputBytes) throw new HwpError('limit')
    const read = admission.read(f.abs, () => allowed().st!, L.inputBytes)
    if (!read) throw new HwpError('changed')
    const { bytes, st } = read
    return { key: `team:${source}`, bytes, hash: sha256(bytes), version: `${st.dev}:${st.ino}:${st.size}:${st.mtimeMs}:${st.ctimeMs}`, ext: /\.hwpx$/i.test(f.name) ? 'hwpx' as const : 'hwp' as const }
  }
  /** A page of a team file the person may read (`source`: its path). */
  page(user: string, source: string, page: number, signal?: AbortSignal, cacheId?: string): Promise<RenderedPage & { id: string }> {
    return this.pageOf(user, (admission) => this.source(user, source, admission), page, signal, cacheId)
  }
  /** A page of a document `open` checks and reads for this person (a team file above; a room file: rooms/files.ts). */
  async pageOf(user: string, open: OpenHwpSource, page: number, signal?: AbortSignal, cacheId?: string): Promise<RenderedPage & { id: string }> {
    const admission = new SearchAdmission(this.files.ctx.files.quarantine)
    try { return await this.admittedPage(user, open, page, admission, signal, cacheId) }
    finally { admission.close() }
  }
  private async admittedPage(user: string, open: OpenHwpSource, page: number, admission: SearchAdmission, signal?: AbortSignal, cacheId?: string): Promise<RenderedPage & { id: string }> {
    if (signal?.aborted) throw new HwpError('cancelled')
    // Check permission even on invalid cache IDs and before busy errors.
    const f = open(admission)
    if (process.platform === 'linux' && this.files.ctx.config.mode === 'prod' && !converterCgroup()) throw new HwpError('isolation')
    if (!Number.isInteger(page) || page < 1 || page > L.pages) throw new HwpError('limit')
    const engine = this.engine
    const key = `${f.key}:${f.version}:${f.hash}:${engine.identity}:${page}`
    for (const [k, c] of this.cache) if (c.expires < Date.now()) this.cache.delete(k)
    const hit = this.cache.get(key)
    if (cacheId && (!hit || hit.id !== cacheId)) throw new HwpError('changed')
    if (hit) return { ...hit.result, id: hit.id }
    if (this.running.has(user) || this.running.size >= L.perServer) throw new HwpError('busy')
    this.running.add(user)
    const generation = this.generation
    const job = new AbortController()
    const onAbort = () => job.abort()
    signal?.addEventListener('abort', onAbort, { once: true })
    this.inflight.add(job)
    try {
      const result = await engine.render(f.bytes, f.ext, page, job.signal)
      if (signal?.aborted) throw new HwpError('cancelled')
      // turned off / updated / rolled back while rendering: the result belongs to a package that is no longer active
      if (generation !== this.generation || job.signal.aborted) throw new HwpError('changed')
      // Includes disabled-account and role/group/ACL changes while the renderer was running (a room file: left the
      // room, the message hidden, deleted or put on the download-only list).
      const now = open(admission)
      if (generation !== this.generation || now.key !== f.key || now.version !== f.version || now.hash !== f.hash) throw new HwpError('changed')
      if (result.meta.sourceHash !== f.hash || result.bytes.length > L.outputBytes) throw new HwpError('damaged')
      let size = result.bytes.length
      for (const c of this.cache.values()) size += c.result.bytes.length
      while ((size > L.cacheBytes || this.cache.size >= 128) && this.cache.size) {
        const first = this.cache.entries().next().value!
        size -= first[1].result.bytes.length; this.cache.delete(first[0])
      }
      const id = randomUUID()
      this.cache.set(key, { key, source: f.key, id, result, expires: Date.now() + 600000 })
      return { ...result, id }
    } finally { this.running.delete(user); this.inflight.delete(job); signal?.removeEventListener('abort', onAbort) }
  }
}
