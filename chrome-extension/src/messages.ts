export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, ko, ja, zh_CN, es, id }

/** One language's messages.json for Chrome: `{app}` filled in, `$1`.. as named placeholders. */
export function chromeMessages(locale: Locale, appName: string): Record<string, { message: string; placeholders?: Record<string, { content: string }> }> {
  const out: Record<string, { message: string; placeholders?: Record<string, { content: string }> }> = {}
  for (const [key, raw] of Object.entries(MESSAGES[locale])) {
    // a literal "$" in Chrome messages is written "$$"; then $1 -> $P1$
    const text = raw.replace(/\{app\}/g, appName.replace(/\$/g, '$$$$'))
    const nums = [...new Set([...text.matchAll(/\$(\d)/g)].map((m) => m[1]))]
    const message = text.replace(/\$(\d)/g, '$P$1$')
    out[key] = nums.length ? { message, placeholders: Object.fromEntries(nums.map((n) => [`p${n}`, { content: `$${n}` }])) } : { message }
  }
  return out
}
